-- TOP EN SON SIPARIS
SELECT TOP(1) 
	*
FROM 
	SALES
ORDER BY DATE_ desc;

-- MAX EN SON SIPARIS
SELECT 
	*
FROM 
	SALES
WHERE DATE_ = (SELECT MAX(DATE_) FROM SALES);



-- MIN EN ESKI SIPARIS
SELECT 
	*
FROM 
	SALES
WHERE DATE_ = (SELECT MIN(DATE_) FROM SALES);


-- TOTALPRICE ORTALAMA
SELECT
	AVG(TOTALPRICE)
FROM
	SALES;


-- EN PAHALI SİPARİŞ AYNI EĞERDEN 3 OLDUĞU İÇİN 3 TANE DÖNDÜ
SELECT
	*
FROM
	SALES
WHERE TOTALPRICE = (SELECT MAX(TOTALPRICE) FROM SALES);



-- %10 ZAM YAPMAK ARTTIRMAK

