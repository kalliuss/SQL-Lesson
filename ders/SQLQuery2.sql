-- ANKARA ISTABUL BURSA GETIR
SELECT 
	* 
FROM 
	CITIES
WHERE CITYNAME IN ('ANKARA', 'İstanbul', 'BURSA')
ORDER BY POPULATION desc;


-- 1 MILYONDAN FAZLA NUFUSU OLANALR
SELECT 
	CITYNAME
FROM 
	CITIES
WHERE POPULATION > 1000000;



-- AKDENİZ VE 3 MİLYONDAN FAZLA NUFUSU OLANLAR
SELECT 
	CITYNAME
	REGION 
FROM 
	CITIES
WHERE REGION = 'Akdeniz' AND POPULATION > 3000000;



